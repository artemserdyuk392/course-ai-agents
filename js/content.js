<p>Три параллельных слоя — реактивный, планирующий и моделирующий — работают одновременно. Специальные управляющие правила (censor rules) определяют, какой слой получает контроль в данный момент. Этот подход избегает жёсткой иерархии, позволяя гибко переключаться между режимами работы.</p>

