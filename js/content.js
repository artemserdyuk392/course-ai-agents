<p>Период расцвета символического подхода породил экспертные системы — программы, основанные на базах знаний и правилах вывода. MYCIN (1976) для диагностики инфекций и R1/XCON (1980) для конфигурирования компьютеров были ранними примерами агентов-советчиков, хотя тогда этот термин ещё не применялся. Эти системы были deliberative: они явно моделировали знания о мире и рассуждали на их основе.</p>

