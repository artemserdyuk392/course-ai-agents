<p>Обучение с подкреплением (Reinforcement Learning, RL) — это парадигма машинного обучения, в которой агент учится принимать решения через взаимодействие со средой. В отличие от обучения с учителем, здесь нет размеченных данных — вместо этого агент получает числовые сигналы вознаграждения (reward), показывающие, насколько хорошо он действует.</p>

