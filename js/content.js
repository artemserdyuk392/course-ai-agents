<p>Теория игр — математический аппарат для анализа стратегического взаимодействия рациональных агентов. Когда решение каждого агента влияет на результаты других, возникает <strong>игра</strong>. Формально игра в нормальной форме определяется тройкой: множество игроков N, множество стратегий для каждого игрока S_i, и функции полезности u_i(s_1, ..., s_n).</p>

